def load_cues(path: Path) -> list[str]:
    """Slugs from a selection CSV: one slug per line, optional `slug` header."""
    slugs: list[str] = []
    for line in path.read_text().splitlines():
        field = line.split(",")[0].strip()
        if field and field.lower() != "slug":
            slugs.append(field)
    return slugs


