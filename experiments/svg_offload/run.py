@lru_cache(maxsize=1)
def svgo_available() -> bool:
    """True when `npx svgo --version` runs clean (svgo present or npx-cached)."""
    if not shutil.which("npx"):
        return False
    try:
        cp = subprocess.run(
            ["npx", "svgo", "--version"],
            capture_output=True, text=True, timeout=180,
            stdin=subprocess.DEVNULL,
        )
        return cp.returncode == 0
    except Exception:
        return False


def svgo_command(raw: Path, out: Path) -> list[str]:
    return ["npx", "svgo", str(raw), "-o", str(out)]


