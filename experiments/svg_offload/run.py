# ---------------------------------------------------------------------------
# Condition A generators — pluggable. Each takes a text prompt and returns
# SVG text. TODO stubs until MLX weights land in ~/.cache/huggingface/hub.


def _hf_has_mlx_weights(name_fragment: str, hub: Path = HF_HUB) -> bool:
    """True when a cached HF repo matching the fragment holds safetensors."""
    if not hub.is_dir():
        return False
    frag = name_fragment.lower()
    for repo in hub.glob("models--*"):
        if frag in repo.name.lower() and any(repo.rglob("*.safetensors")):
            return True
    return False


def _todo_svg(model: str, prompt: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">\n'
        f"  <!-- TODO: no MLX weights for {model} under {HF_HUB}; placeholder asset -->\n"
        f"  <!-- prompt: {prompt} -->\n"
        f'  <rect x="4" y="4" width="40" height="40" rx="6" fill="none" stroke="currentColor" stroke-width="2"/>\n'
        f'  <circle cx="24" cy="24" r="8" fill="none" stroke="currentColor" stroke-width="2"/>\n'
        f"</svg>\n"
    )


def svgen_7b(prompt: str) -> str:
    """svgen-7b local MLX text-to-SVG generator."""
    if not _hf_has_mlx_weights("svgen"):
        return _todo_svg("svgen-7b", prompt)
    # TODO: load MLX weights and decode SVG tokens for the prompt.
    return _todo_svg("svgen-7b", prompt)


def omnisvg_1_1(prompt: str) -> str:
    """OmniSVG 1.1 local MLX text-to-SVG generator."""
    if not _hf_has_mlx_weights("omnisvg"):
        return _todo_svg("omnisvg-1.1", prompt)
    # TODO: load MLX weights and decode SVG tokens for the prompt.
    return _todo_svg("omnisvg-1.1", prompt)


GENERATORS = {"svgen-7b": svgen_7b, "omnisvg-1.1": omnisvg_1_1}


@lru_cache(maxsize=1)
def svgo_available() -> bool:
    """True when `npx svgo --version` runs clean (svgo present or npx-cached)."""
    if not shutil.which("npx"):
        return False
    try:
        cp = subprocess.run(
            ["npx", "svgo", "--version"],
            capture_output=True, text=True, timeout=180,
        )
        return cp.returncode == 0
    except Exception:
        return False


def svgo_command(raw: Path, out: Path) -> list[str]:
    return ["npx", "svgo", str(raw), "-o", str(out)]


# ---------------------------------------------------------------------------
# Workers


@dataclass(frozen=True)
class Worker:
    slug: str
    agent: str  # stage_dispatch --agent value, or "muse" for the direct CLI
    model: str


WORKERS = [
    Worker("agy-gemini-flash-low", "agy", "gemini-3.8-flash-low"),
    Worker("codex-gpt-luna", "codex", "gpt-5.6-luna"),
    Worker("codex-gpt-terra", "codex", "gpt-5.6-terra"),
    Worker("muse", "muse", "muse"),
]

CONDITIONS = ("A", "B")


def worker_command(
    worker: Worker,
    brief_path: Path,
    worktree: Path,
    candidate: Candidate,
    condition: str,
) -> list[str]:
    """Dispatch command for one (cue, condition, worker) cell."""
    if worker.agent == "muse":
        return [
            "muse", "exec",
            "--workspace", str(worktree),
            "--prompt-file", str(brief_path),
        ]
    return [
        sys.executable, "-m", "scriptcast.tools.stage_dispatch", "start",
        "--agent", worker.agent,
        "--model", worker.model,
        "--brief", str(brief_path),
        "--worktree", str(worktree),
        "--project", "svg_offload",
        "--task", f"{candidate.slug}-{condition}-{worker.slug}",
        "--kind", "experiment",
    ]


# ---------------------------------------------------------------------------
# Briefs


def brief_text(
    candidate: Candidate,
    condition: str,
    worker: Worker,
    stage_dir: Path,
    asset_path: Path | None,
) -> str:
    base = (
        f"# E3 SVG offload — {candidate.slug} (condition {condition})\n\n"
        f"Scene: `{stage_dir / candidate.file}` (asset currently at line {candidate.line})\n"
        f"Cue: `{candidate.cue}` (shot {candidate.shot}, scene {candidate.scene})\n"
        f"Asset: {candidate.asset}\n\n"
    )
    if condition == "A":
        return base + (
            f"The vector asset has been pre-generated by a local SVG model and\n"
            f"svgo-normalised at `{asset_path}`. Do NOT redraw it.\n\n"
            f"Mount the asset into the scene at cue `{candidate.cue}`: import or inline the\n"
            f"SVG markup from that file, position it per the scene layout, and gate its\n"
            f"entrance animation on the cue timing. Keep the scene's existing stroke/fill\n"
            f"token usage (`color('color/...')`) where the asset references `currentColor`.\n"
        )
    return base + (
        f"Draw the asset yourself, inline in the scene TSX at cue `{candidate.cue}`.\n\n"
        f"Write SVG markup matching the description above, sized to a 48px viewBox for\n"
        f"icons or the scene's layout box for diagrams, gated on the cue timing, using the\n"
        f"scene's design tokens (`color('color/...')`).\n"
    )


# ---------------------------------------------------------------------------
# Metrics


RESULTS_HEADER = [
    "cue", "scene", "shot", "file", "cue_id", "condition",
    "worker", "agent", "model", "generator", "brief",
    "worker_tokens", "tsx_typecheck_pass", "render_pass",
    "svg_node_count", "svg_bytes", "critic_verdict",
]

CRITIC_PLACEHOLDER = "PENDING"

SVG_NODE_RE = re.compile(
    r"<(svg|g|path|rect|circle|ellipse|line|polyline|polygon|text|tspan|defs|marker|mask|use|image)\b"
)

TOKEN_PATTERNS = [
    re.compile(r'"totalTokens"\s*:\s*(\d+)'),
    re.compile(r'"total_tokens"\s*:\s*(\d+)'),
    re.compile(r"tokens?\s+used[:\s]+(\d+)", re.IGNORECASE),
]


def parse_tokens(output: str) -> int | None:
    """Worker token count when the CLI reports one; else None."""
    for pat in TOKEN_PATTERNS:
        m = pat.search(output)
        if m:
            return int(m.group(1))
    return None


def svg_stats(svg_text: str) -> tuple[int, int]:
    """(element count, byte length). Regex-based: JSX braces in TSX-inline SVG
    break XML parsers, so both conditions use the same element counter."""
    return len(SVG_NODE_RE.findall(svg_text)), len(svg_text.encode("utf-8"))


def extract_inline_svgs(tsx_path: Path) -> str:
    """All <svg>...</svg> blocks from a scene file, concatenated."""
    if not tsx_path.is_file():
        return ""
    text = tsx_path.read_text()
    return "\n".join(re.findall(r"<svg\b[\s\S]*?</svg>", text))


def tsx_typecheck(stage_dir: Path) -> str:
    """pass/fail/skip for `npx tsc --noEmit` against the stage tsconfig."""
    tsconfig = stage_dir / "tsconfig.json"
    if not tsconfig.is_file() or not shutil.which("npx"):
        return "skip"
    cp = subprocess.run(
        ["npx", "tsc", "--noEmit", "-p", str(tsconfig)],
        capture_output=True, text=True, cwd=str(stage_dir),
    )
    return "pass" if cp.returncode == 0 else "fail"


def render_check(render_cmd: str | None, candidate: Candidate, cwd: Path) -> str:
    """pass/fail/skip for the scene render probe.

    --render-cmd is a template; {scene} and {frame} are substituted. Without
    it there is no grounded render entry point, so the probe is skipped.
    """
    if not render_cmd:
        return "skip"
    cmd = shlex.split(render_cmd.format(scene=candidate.scene, frame=0))
    if not shutil.which(cmd[0]):
        return "skip"
    cp = subprocess.run(cmd, capture_output=True, text=True, cwd=str(cwd))
    return "pass" if cp.returncode == 0 else "fail"


# ---------------------------------------------------------------------------
# Plan + run


@dataclass
class PlannedCommand:
    cue: str
    condition: str
    worker: str
    command: list[str]


def build_plan(args: argparse.Namespace) -> tuple[list[str], list[PlannedCommand]]:
    """(comment lines, shell commands) for the whole matrix."""
    stage_dir: Path = args.stage_dir
    worktree: Path = args.worktree
    out_dir: Path = args.out_dir
    candidates = [c for c in CANDIDATES if c.slug in args.cues]
    workers = [w for w in WORKERS if w.slug in args.workers]

    comments: list[str] = []
    commands: list[PlannedCommand] = []
    for cand in candidates:
        raw_svg = out_dir / "assets" / f"{cand.slug}.{args.generator}.raw.svg"
        norm_svg = out_dir / "assets" / f"{cand.slug}.{args.generator}.svg"
        if "A" in args.conditions:
            comments.append(
                f"# generate cue={cand.slug} generator={args.generator} -> {raw_svg}"
            )
            commands.append(
                PlannedCommand(cand.slug, "A", "(svgo)", svgo_command(raw_svg, norm_svg))
            )
        for condition in args.conditions:
            for worker in workers:
                brief = (
                    out_dir / "briefs" / f"{cand.slug}-{condition}-{worker.slug}.md"
                )
                comments.append(f"# write brief {brief}")
                commands.append(
                    PlannedCommand(
                        cand.slug,
                        condition,
                        worker.slug,
                        worker_command(worker, brief, worktree, cand, condition),
                    )
                )
    return comments, commands


def run_cell(
    candidate: Candidate,
    condition: str,
    worker: Worker,
    args: argparse.Namespace,
    asset_path: Path | None,
) -> dict[str, object]:
    """Execute one (cue, condition, worker) cell and return its CSV row."""
    out_dir: Path = args.out_dir
    brief = out_dir / "briefs" / f"{candidate.slug}-{condition}-{worker.slug}.md"
    brief.parent.mkdir(parents=True, exist_ok=True)
    brief.write_text(
        brief_text(candidate, condition, worker, args.stage_dir, asset_path)
    )
    cmd = worker_command(worker, brief, args.worktree, candidate, condition)
    cp = subprocess.run(
        cmd, capture_output=True, text=True, cwd=str(args.worktree)
    )
    tokens = parse_tokens(cp.stdout + "\n" + cp.stderr)

    if condition == "A" and asset_path and asset_path.is_file():
        nodes, nbytes = svg_stats(asset_path.read_text())
    else:
        nodes, nbytes = svg_stats(
            extract_inline_svgs(args.stage_dir / candidate.file)
        )

    return {
        "cue": candidate.slug,
        "scene": candidate.scene,
        "shot": candidate.shot,
        "file": candidate.file,
        "cue_id": candidate.cue,
        "condition": condition,
        "worker": worker.slug,
        "agent": worker.agent,
        "model": worker.model,
        "generator": args.generator if condition == "A" else "",
        "brief": str(brief),
        "worker_tokens": tokens if tokens is not None else "",
        "tsx_typecheck_pass": tsx_typecheck(args.stage_dir),
        "render_pass": render_check(args.render_cmd, candidate, args.worktree),
        "svg_node_count": nodes,
        "svg_bytes": nbytes,
        "critic_verdict": CRITIC_PLACEHOLDER,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cues", default=",".join(DEFAULT_CUES),
                    help="comma-separated candidate slugs (default: the 10 stand-ins)")
    ap.add_argument("--workers", default=",".join(w.slug for w in WORKERS),
                    help="comma-separated worker slugs")
    ap.add_argument("--conditions", default="A,B", help="subset of A,B")
    ap.add_argument("--generator", default="svgen-7b", choices=sorted(GENERATORS),
                    help="condition A local generator")
    ap.add_argument("--stage-dir", type=Path, default=DEFAULT_STAGE_DIR)
    ap.add_argument("--worktree", type=Path, default=DEFAULT_WORKTREE,
                    help="worktree the dispatched workers operate in")
    ap.add_argument("--out-dir", type=Path, default=EXPERIMENT_DIR / "out")
    ap.add_argument("--results", type=Path, default=EXPERIMENT_DIR / "results.csv")
    ap.add_argument("--render-cmd", default=None,
                    help="render probe template, e.g. 'npx remotion still {scene} /tmp/e3.png --frame={frame}'")
    ap.add_argument("--dry-run", action="store_true",
                    help="print every planned command; run and write nothing")
    args = ap.parse_args(argv)

    args.cues = [s.strip() for s in args.cues.split(",") if s.strip()]
    args.workers = [s.strip() for s in args.workers.split(",") if s.strip()]
    args.conditions = [s.strip().upper() for s in args.conditions.split(",") if s.strip()]
    unknown = set(args.cues) - {c.slug for c in CANDIDATES}
    if unknown:
        ap.error(f"unknown cue slugs: {sorted(unknown)}")
    unknown_w = set(args.workers) - {w.slug for w in WORKERS}
    if unknown_w:
        ap.error(f"unknown worker slugs: {sorted(unknown_w)}")
    bad_cond = set(args.conditions) - set(CONDITIONS)
    if bad_cond:
        ap.error(f"unknown conditions: {sorted(bad_cond)}")

    comments, commands = build_plan(args)

    if args.dry_run:
        print(f"# E3 svg_offload plan: {len(args.cues)} cues x "
              f"{len(args.conditions)} conditions x {len(args.workers)} workers")
        for line in comments:
            print(line)
        for planned in commands:
            print(f"[dry-run] {shlex.join(planned.command)}")
        return 0

    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_header = not args.results.is_file()
    args.results.parent.mkdir(parents=True, exist_ok=True)

    candidates = [c for c in CANDIDATES if c.slug in args.cues]
    workers = [w for w in WORKERS if w.slug in args.workers]
    use_svgo = svgo_available()

    with open(args.results, "a", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=RESULTS_HEADER)
        if write_header:
            writer.writeheader()
        for cand in candidates:
            asset_path = None
            if "A" in args.conditions:
                raw_svg = args.out_dir / "assets" / f"{cand.slug}.{args.generator}.raw.svg"
                norm_svg = args.out_dir / "assets" / f"{cand.slug}.{args.generator}.svg"
                raw_svg.parent.mkdir(parents=True, exist_ok=True)
                raw_svg.write_text(GENERATORS[args.generator](cand.asset))
                if use_svgo:
                    cp = subprocess.run(
                        svgo_command(raw_svg, norm_svg),
                        capture_output=True, text=True,
                    )
                    asset_path = norm_svg if cp.returncode == 0 else raw_svg
                else:
                    shutil.copyfile(raw_svg, norm_svg)
                    asset_path = norm_svg
            for condition in args.conditions:
                for worker in workers:
                    row = run_cell(cand, condition, worker, args, asset_path)
                    writer.writerow(row)
    print(f"wrote {args.results}")
    return 0


if __name__ == "__main__":
    import os

    try:
        rc = main()
        sys.stdout.flush()  # pipe-close surfaces here, not inside main()
    except BrokenPipeError:  # piped into head(1) etc.
        devnull = os.open(os.devnull, os.O_WRONLY)
        os.dup2(devnull, sys.stdout.fileno())
        rc = 0
    raise SystemExit(rc)
